export function demoEvents(id: string): TrackingEvent[] {
  const s = demoShipments.find(s => s.id === id);
  return s
    ? [
        {
          id: `demo-${id}`,
          provider: "Demo logistics feed",
          eventType: s.status,
          occurredAt: s.observedAt!,
          receivedAt: s.receivedAt,
        },
      ]
    : [];
}
